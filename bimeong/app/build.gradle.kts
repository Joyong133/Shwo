// Release signing is optional: put signing/keystore.properties next to your keystore
// (see README). Without it the release build is signed with the debug key so that
// it can still be installed.
val keystoreProps = Properties().apply {
    val f = rootProject.file("signing/keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "app.bimeong"
    compileSdk = 36

    defaultConfig {
        applicationId = "app.bimeong"
        minSdk = 26
        targetSdk = 36
        versionCode = 2
        versionName = "1.1.0"
    }

    signingConfigs {
        if (keystoreProps.containsKey("storeFile")) {
            create("release") {
                storeFile = rootProject.file("signing/${keystoreProps.getProperty("storeFile")}")
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    testOptions {
        unitTests {
            isIncludeAndroidResources = true
            all {
                it.systemProperty("roborazzi.test.record", "true")
                it.systemProperty("robolectric.graphicsMode", "NATIVE")
                // Optional mirror for Robolectric's Android runtime download, e.g. in ~/.gradle/gradle.properties:
                //   systemProp.robolectric.dependency.repo.url=https://...
                System.getProperty("robolectric.dependency.repo.url")?.let { url ->
                    it.systemProperty("robolectric.dependency.repo.url", url)
                }
                it.maxHeapSize = "2g"
            }
        }
    }
}

